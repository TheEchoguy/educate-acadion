"""
Shared Quality Assurance (QA) Engine for Acadion PPT Generator.
Performs automated structural, typographical, and diversity quality assurance
checks across presentations generated by Acadion Native Engine.
"""

import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Dict, List, Optional
import pptx
from pptx.util import Inches

from app.models import PresentationData, UnifiedPresentationPlan


@dataclass
class QACheckResult:
    """Result of an individual quality check."""
    name: str
    passed: bool
    score: int          # 0 to 100
    detail: str
    severity: str = "warning"  # "info", "warning", "critical"


@dataclass
class QAReport:
    """Comprehensive presentation quality assessment report."""
    status: str                         # "pass", "warning", "fail"
    overall_score: int                  # 0 to 100
    checks: List[QACheckResult] = field(default_factory=list)
    cards_grid_ratio: float = 0.0
    consecutive_repetition_count: int = 0
    total_slides: int = 0
    archetypes_used: List[str] = field(default_factory=list)
    recommendations: List[str] = field(default_factory=list)

    @property
    def is_acceptable(self) -> bool:
        """True if no critical failures and overall score >= 75."""
        has_critical_failure = any(not c.passed and c.severity == "critical" for c in self.checks)
        return not has_critical_failure and self.overall_score >= 75


class PresentationQAEngine:
    """Evaluates presentations against professional instructional design standards."""

    MAX_CARDS_GRID_RATIO = 0.25  # Max 25% cards grid in deck
    TARGET_ASPECT_RATIO = 16 / 9 # Widescreen 16:9
    MIN_BODY_FONT_PT = 10.0
    MIN_SLIDES = 2

    def evaluate_presentation(
        self,
        pptx_path: str | Path,
        plan_or_data: Optional[UnifiedPresentationPlan | PresentationData] = None,
    ) -> QAReport:
        """Run all automated QA checks on a generated PowerPoint file."""
        file_path = Path(pptx_path)
        checks: List[QACheckResult] = []
        recommendations: List[str] = []

        # 1. PPTX File & Schema Integrity
        if not file_path.exists():
            return QAReport(
                status="fail",
                overall_score=0,
                checks=[QACheckResult(name="File Existence", passed=False, score=0, detail="PPTX file not found on disk", severity="critical")],
            )

        try:
            prs = pptx.Presentation(str(file_path))
        except Exception as e:
            return QAReport(
                status="fail",
                overall_score=0,
                checks=[QACheckResult(name="PPTX Load", passed=False, score=0, detail=f"Corrupted or invalid PPTX: {str(e)}", severity="critical")],
            )

        total_slides = len(prs.slides)
        checks.append(QACheckResult(
            name="PPTX Schema Validity",
            passed=True,
            score=100,
            detail=f"Presentation XML structure is valid with {total_slides} slides.",
            severity="info",
        ))

        # 2. Slide Count & Minimum Content Check
        slide_count_passed = total_slides >= self.MIN_SLIDES
        checks.append(QACheckResult(
            name="Slide Count Sufficiency",
            passed=slide_count_passed,
            score=100 if slide_count_passed else 40,
            detail=f"Deck contains {total_slides} slides (minimum {self.MIN_SLIDES}).",
            severity="warning" if not slide_count_passed else "info",
        ))

        # 3. Canvas Aspect Ratio (16:9 Widescreen Check)
        width_in = prs.slide_width.inches
        height_in = prs.slide_height.inches
        ratio = width_in / height_in if height_in > 0 else 0
        is_widescreen = abs(ratio - self.TARGET_ASPECT_RATIO) < 0.05
        checks.append(QACheckResult(
            name="16:9 Widescreen Canvas",
            passed=is_widescreen,
            score=100 if is_widescreen else 70,
            detail=f"Canvas dimensions: {width_in:.2f}\" x {height_in:.2f}\" (Aspect ratio: {ratio:.2f}:1).",
            severity="info" if is_widescreen else "warning",
        ))

        # 4. Empty Slide Detection & Shape Count
        empty_slides = [idx + 1 for idx, s in enumerate(prs.slides) if len(s.shapes) == 0]
        has_empty = len(empty_slides) > 0
        checks.append(QACheckResult(
            name="Slide Content Populated",
            passed=not has_empty,
            score=100 if not has_empty else 0,
            detail="All slides contain rendered visual shapes." if not has_empty else f"Empty slides detected: {empty_slides}",
            severity="critical" if has_empty else "info",
        ))

        # 5. Plan Diversity & Repetition Analysis (if plan provided)
        archetypes: List[str] = []
        cards_grid_count = 0
        consecutive_repeats = 0

        if plan_or_data:
            if isinstance(plan_or_data, UnifiedPresentationPlan):
                archetypes = [s.archetype.value if hasattr(s.archetype, "value") else str(s.archetype) for s in plan_or_data.slides]
            elif isinstance(plan_or_data, PresentationData):
                archetypes = [s.composition_type or "editorial" for s in plan_or_data.content_sections]

            # Count cards grid
            for a in archetypes:
                if a in ("cards_grid", "cards"):
                    cards_grid_count += 1

            # Count consecutive duplicates
            for i in range(1, len(archetypes)):
                if archetypes[i] == archetypes[i - 1]:
                    consecutive_repeats += 1

        cards_ratio = (cards_grid_count / len(archetypes)) if archetypes else 0.0
        diversity_passed = cards_ratio <= self.MAX_CARDS_GRID_RATIO and consecutive_repeats <= 1

        checks.append(QACheckResult(
            name="Visual Composition Diversity",
            passed=diversity_passed,
            score=100 if diversity_passed else max(50, int(100 - (cards_ratio * 100) - (consecutive_repeats * 15))),
            detail=f"Cards grid ratio: {cards_ratio:.1%} (max {self.MAX_CARDS_GRID_RATIO:.0%}); Consecutive identical layouts: {consecutive_repeats}.",
            severity="warning" if not diversity_passed else "info",
        ))

        if cards_ratio > self.MAX_CARDS_GRID_RATIO:
            recommendations.append("Reduce repetitive card boxes; diversify with editorial text, quotes, or matrices.")
        if consecutive_repeats > 0:
            recommendations.append("Avoid placing identical layout archetypes on consecutive slides.")

        # 6. Speaker Notes Retention Check
        slides_with_notes = 0
        for slide in prs.slides:
            try:
                if slide.has_notes_slide and slide.notes_slide.notes_text_frame.text.strip():
                    slides_with_notes += 1
            except Exception:
                pass

        notes_ratio = (slides_with_notes / total_slides) if total_slides > 0 else 0
        notes_passed = notes_ratio >= 0.70
        checks.append(QACheckResult(
            name="Speaker Notes Coverage",
            passed=notes_passed,
            score=int(notes_ratio * 100),
            detail=f"{slides_with_notes}/{total_slides} slides ({notes_ratio:.0%}) contain instructor speaker notes.",
            severity="warning" if not notes_passed else "info",
        ))

        # 7. Text Density & Potential Overflow Estimation
        dense_slides = []
        for idx, slide in enumerate(prs.slides):
            total_chars = 0
            for shape in slide.shapes:
                if shape.has_text_frame:
                    total_chars += len(shape.text_frame.text)
            if total_chars > 800:
                dense_slides.append((idx + 1, total_chars))

        density_passed = len(dense_slides) == 0
        checks.append(QACheckResult(
            name="Text Density & Overflow Guard",
            passed=density_passed,
            score=100 if density_passed else max(60, 100 - (len(dense_slides) * 15)),
            detail="Text density balanced across slides." if density_passed else f"Overcrowded text detected on slide(s): {[s[0] for s in dense_slides]}.",
            severity="warning" if not density_passed else "info",
        ))

        # 8. Header Divider Clearance (No collision between titles and horizontal rules)
        divider_collisions = []
        for s_idx, slide in enumerate(prs.slides):
            rules = [
                s for s in slide.shapes
                if s.width >= Inches(4.5) and s.height <= Inches(0.06) and Inches(0.9) <= s.top <= Inches(2.2)
            ]
            titles = [
                s for s in slide.shapes
                if s.has_text_frame
                and Inches(0.5) <= s.top <= Inches(1.2)
                and s.height <= Inches(2.0)
                and s.width < prs.slide_width * 0.95
                and s.text_frame.text.strip()
                and s not in rules
            ]
            for r in rules:
                for t in titles:
                    if t.top + t.height > r.top + Inches(0.02):
                        t_bottom_in = (t.top + t.height) / Inches(1)
                        r_top_in = r.top / Inches(1)
                        divider_collisions.append((s_idx + 1, f"Slide {s_idx + 1}: Title text box (bottom={t_bottom_in:.2f}\") intersects divider rule (top={r_top_in:.2f}\")"))

        divider_passed = len(divider_collisions) == 0
        checks.append(QACheckResult(
            name="Header Divider Clearance",
            passed=divider_passed,
            score=100 if divider_passed else 20,
            detail="All slide headers maintain clean vertical clearance above accent dividers." if divider_passed else f"Divider collision detected on slide(s): {[c[0] for c in divider_collisions]}.",
            severity="critical" if not divider_passed else "info",
        ))

        # 9. Shape Collision & Intentional Containment Guard
        genuine_overlaps = []
        for s_idx, slide in enumerate(prs.slides):
            content_shapes = [
                s for s in slide.shapes
                if not (s.width >= prs.slide_width * 0.94 and s.height >= prs.slide_height * 0.85)
                and s.width > Inches(0.1) and s.height > Inches(0.1)
            ]
            for i in range(len(content_shapes)):
                s1 = content_shapes[i]
                for j in range(i + 1, len(content_shapes)):
                    s2 = content_shapes[j]
                    x_left = max(s1.left, s2.left)
                    y_top = max(s1.top, s2.top)
                    x_right = min(s1.left + s1.width, s2.left + s2.width)
                    y_bottom = min(s1.top + s1.height, s2.top + s2.height)

                    if x_right > x_left + Inches(0.10) and y_bottom > y_top + Inches(0.10):
                        inter_area = (x_right - x_left) * (y_bottom - y_top)
                        area1 = s1.width * s1.height
                        area2 = s2.width * s2.height
                        min_area = min(area1, area2)

                        # Intentional containment: text box inside card, icon inside badge, strip inside card
                        is_contained = (inter_area >= 0.80 * min_area)
                        if not is_contained:
                            genuine_overlaps.append((s_idx + 1, f"Slide {s_idx + 1}: Unintentional overlap between shapes at ({s1.left.inches:.2f}\", {s1.top.inches:.2f}\") and ({s2.left.inches:.2f}\", {s2.top.inches:.2f}\")"))

        overlap_passed = len(genuine_overlaps) == 0
        checks.append(QACheckResult(
            name="Shape Collision & Containment Guard",
            passed=overlap_passed,
            score=100 if overlap_passed else 40,
            detail="No unintentional shape collisions detected; intentional containments verified." if overlap_passed else f"Collisions detected: {[o[1] for o in genuine_overlaps[:3]]}.",
            severity="warning" if not overlap_passed else "info",
        ))

        # 10. Slide Boundary & Safe Margin Guard
        out_of_bounds = []
        for s_idx, slide in enumerate(prs.slides):
            for s in slide.shapes:
                if s.left < -Inches(0.15) or s.top < -Inches(0.15) or (s.left + s.width) > prs.slide_width + Inches(0.15) or (s.top + s.height) > prs.slide_height + Inches(0.15):
                    out_of_bounds.append((s_idx + 1, f"Slide {s_idx + 1}: Shape extends beyond slide boundaries"))

        bounds_passed = len(out_of_bounds) == 0
        checks.append(QACheckResult(
            name="Slide Boundary & Safe Margins",
            passed=bounds_passed,
            score=100 if bounds_passed else 50,
            detail="All visual elements respect 16:9 canvas boundaries and safe margins." if bounds_passed else f"Out-of-bounds shapes on slide(s): {[b[0] for b in out_of_bounds]}.",
            severity="warning" if not bounds_passed else "info",
        ))

        # 11. Canvas Whitespace & Layout Balance Guard
        whitespace_defects = []
        for s_idx, slide in enumerate(prs.slides):
            body_cards = [
                s for s in slide.shapes
                if Inches(1.5) <= s.top <= Inches(3.0) and s.height >= Inches(3.0) and s.width < prs.slide_width * 0.90
            ]
            if len(body_cards) == 1 and body_cards[0].width <= Inches(4.5):
                whitespace_defects.append((s_idx + 1, f"Slide {s_idx + 1}: Single narrow card ({body_cards[0].width.inches:.2f}\") creates excessive whitespace void"))

        whitespace_passed = len(whitespace_defects) == 0
        checks.append(QACheckResult(
            name="Canvas Whitespace & Layout Balance",
            passed=whitespace_passed,
            score=100 if whitespace_passed else 35,
            detail="Slide layouts distribute content symmetrically across widescreen canvas." if whitespace_passed else f"Excessive whitespace defect on slide(s): {[w[0] for w in whitespace_defects]}.",
            severity="warning" if not whitespace_passed else "info",
        ))

        # 12. Heading Semantic Integrity & Step Dispersion Guard
        step_heading_defects = []
        for s_idx, slide in enumerate(prs.slides):
            for s in slide.shapes:
                if s.has_text_frame and s.top <= Inches(1.3):
                    txt = s.text_frame.text.strip()
                    step_matches = re.findall(r"(?:^|(?<=\s))(?:(?:Step|Phase|Stage)\s*\d+[:\.]?|\d+[\.\)])\s+[A-Za-z]", txt, re.IGNORECASE)
                    if len(step_matches) >= 2:
                        step_heading_defects.append((s_idx + 1, txt[:60]))

        dispersion_passed = len(step_heading_defects) == 0
        checks.append(QACheckResult(
            name="Heading Semantic Integrity & Step Dispersion",
            passed=dispersion_passed,
            score=100 if dispersion_passed else 25,
            detail="Slide headings represent concise topic overviews with discrete process units." if dispersion_passed else f"Concatenated multi-step headings on slide(s): {[d[0] for d in step_heading_defects]}.",
            severity="critical" if not dispersion_passed else "info",
        ))

        # Overall Score Calculation
        avg_score = int(sum(c.score for c in checks) / len(checks)) if checks else 100
        overall_status = "pass" if avg_score >= 80 and not any(not c.passed and c.severity == "critical" for c in checks) else "warning"

        return QAReport(
            status=overall_status,
            overall_score=avg_score,
            checks=checks,
            cards_grid_ratio=cards_ratio,
            consecutive_repetition_count=consecutive_repeats,
            total_slides=total_slides,
            archetypes_used=archetypes,
            recommendations=recommendations,
        )
